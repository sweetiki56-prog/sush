export function runtimeLineForDisplay(source: string, locale: 'ru' | 'en'): string {
  if (locale === 'ru') return source;
  const exact = en.get(source);
  if (exact) return exact;
  for (const [pattern, translate] of corePatterns) {
    const match = source.match(pattern);
    if (match) return translate(...match);
  }
  for (const [pattern, translate] of roadPatterns) {
    const match = source.match(pattern);
    if (match) return translate(...match);
  }
  return source;
}
