export function chapterText(source: string, locale: Locale): string {
  if (locale !== 'en') return source;
  if (en[source]) return en[source];
  const level = source.match(/^(.*), уровень (\d+)$/);
  if (level) return `${heroNameForDisplay(level[1], 'en')}, level ${level[2]}`;
  const checks = source.match(/^(\d+) успех \/ (\d+) провал$/);
  if (checks) return `${checks[1]} passed / ${checks[2]} failed`;
  const time = source.match(/^(\d+) мин (\d+) с$/);
  if (time) return `${time[1]} min ${time[2]} sec`;
  return source;
}
